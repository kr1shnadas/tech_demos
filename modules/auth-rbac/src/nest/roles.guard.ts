import "reflect-metadata";
import { CanActivate, ExecutionContext, ForbiddenException, Inject, Injectable } from "@nestjs/common";
import { Reflector } from "@nestjs/core";
import { evaluateAccess, type AuthUser } from "../access/evaluate-access.js";
import { ROLES_KEY } from "./constants.js";

@Injectable()
export class RolesGuard implements CanActivate {
  constructor(@Inject(Reflector) private readonly reflector: Reflector) {}

  canActivate(context: ExecutionContext): boolean {
    const required = this.reflector.getAllAndOverride<readonly string[] | undefined>(ROLES_KEY, [
      context.getHandler(),
      context.getClass(),
    ]);
    if (!required || required.length === 0) return true;

    const request = context.switchToHttp().getRequest<{ user?: AuthUser }>();
    const decision = evaluateAccess(request.user, required);
    if (!decision.allowed) {
      throw new ForbiddenException(decision.reason);
    }
    return true;
  }
}

